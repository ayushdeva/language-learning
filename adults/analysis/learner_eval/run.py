"""Run every baseline on SLAM and write a markdown report.

    uv run python -m learner_eval.run                          # reverse_translate, all tracks
    uv run python -m learner_eval.run --formats listen --tracks es_en
"""

import argparse
import json
import time
from pathlib import Path

import numpy as np
import pandas as pd

from . import data, metrics
from .boosted import ProfileGBDT
from .predictors import BASELINES, Population, ProfileLR, replay
from .profile import CountUpdater, DecayUpdater

# each entry builds a fresh model; a model may bring its own update rule (`updater`)
MODELS = [*BASELINES, lambda: ProfileGBDT(updater=DecayUpdater(half_life=3.0))]

REPORTS = Path(__file__).parent / "reports"


def run_track(track: str, formats: tuple[str, ...]) -> dict:
    t0 = time.time()
    ds = data.load(track, formats)
    train = ds.only("train", "dev")   # everything before test; dev was used for tuning boosted.py
    pop = Population(train)
    updater = CountUpdater()
    n_users = len({t.user for t in ds.tasks})
    n_test = int(sum(len(y) for t, y in zip(ds.tasks, ds.outcomes) if t.split == "test"))
    print(f"{track}: {n_users} learners, {n_test:,} test tokens, base rate {pop.base:.3f} (loaded in {time.time() - t0:.0f}s)")

    out = {"track": track, "n_users": n_users, "n_train_tokens": int(sum(len(y) for y in train.outcomes)),
           "n_test_tokens": n_test, "base_rate": pop.base, "models": {}, "descriptions": {}}
    for make in MODELS:
        t0 = time.time()
        model = make()
        up = getattr(model, "updater", None) or updater
        model.fit(train, pop, up)
        rows = {"ex": [], "history": [], "y": [], "p": []}
        seen = {}

        def predict(profile, task, wrong):
            h = seen.get(task.user, 0)
            seen[task.user] = h + 1
            if task.split != "test":
                return
            p = model.predict(profile, task)
            rows["ex"] += [len(rows["y"])] * len(p)
            rows["history"] += [h] * len(p)
            rows["y"].append(wrong)
            rows["p"].append(p)

        replay(ds, up, predict)   # profiles see train + dev, only test is scored
        df = pd.DataFrame({"ex": rows["ex"], "history": rows["history"],
                           "y": np.concatenate(rows["y"]), "p": np.concatenate(rows["p"])})
        res = metrics.score(df, pop.base)
        res["by_history"] = metrics.skill_by_history(df, pop.base)
        if isinstance(model, ProfileLR):
            res["coef"] = {k: float(v) for k, v in model.coef.items()}
            res["calibration"] = metrics.calibration(df).reset_index(drop=True).to_dict("records")
        out["models"][model.name] = res
        out["descriptions"][model.name] = model.description
        print(f"  {model.name:24s} skill {res['skill']:+.3f}  AUROC {res['auroc']:.3f}  "
              f"within-ex {res['auroc_within_ex']:.3f}  ({time.time() - t0:.0f}s)")
    return out


def fmt(x: float, signed: bool = False) -> str:
    return f"{x:+.3f}" if signed else f"{x:.3f}"


def report(results: list[dict], formats: tuple[str, ...]) -> str:
    names = list(results[0]["models"])
    tracks = [r["track"] for r in results]
    mean = lambda m, k: float(np.mean([r["models"][m][k] for r in results]))
    L = [f"# Learner-profile eval: {', '.join(formats)}", "",
         "Generated by `uv run python -m learner_eval.run`. SLAM's own split: each learner's exercises are train, "
         "then dev, then test (the last ~10%) in time order. Every learner is replayed in time order: predict P(wrong) "
         "for every token of the next exercise from the profile, then update the profile. Only test exercises are "
         "scored. Population statistics and model weights are fitted on train + dev (everything before test), as in the "
         "SLAM shared task's final phase; dev was used earlier to tune `profile_gbdt`.", "",
         "## Data", "", "| track | learners | train + dev tokens | test tokens | base error rate |", "|---|---|---|---|---|"]
    for r in results:
        L.append(f"| {r['track']} | {r['n_users']:,} | {r['n_train_tokens']:,} | {r['n_test_tokens']:,} | {r['base_rate']:.3f} |")

    L += ["", "## Models", "", "| model | what it does |", "|---|---|"]
    L += [f"| `{m}` | {d} |" for m, d in results[0]["descriptions"].items()]

    L += ["", "## Results (mean over tracks)", "",
          "| model | skill | AUROC | AUROC within exercise | F1@0.5 |", "|---|---|---|---|---|"]
    for m in names:
        L.append(f"| `{m}` | **{fmt(mean(m, 'skill'), True)}** | {fmt(mean(m, 'auroc'))} | "
                 f"{fmt(mean(m, 'auroc_within_ex'))} | {fmt(mean(m, 'f1@0.5'))} |")

    for k, title in [("skill", "Skill"), ("auroc", "AUROC")]:
        L += ["", f"## {title} by track", "", "| model | " + " | ".join(tracks) + " |", "|---|" + "---|" * len(tracks)]
        for m in names:
            L.append(f"| `{m}` | " + " | ".join(fmt(r["models"][m][k], k == "skill") for r in results) + " |")

    bins = metrics.HISTORY_LABELS
    L += ["", "## Skill by how much history the learner had (exercises of this type seen before, mean over tracks)", "",
          "| model | " + " | ".join(bins) + " |", "|---|" + "---|" * len(bins)]
    for m in names:
        vals = [[r["models"][m]["by_history"][b] for r in results if b in r["models"][m]["by_history"]] for b in bins]
        cells = [fmt(np.mean(v), True) if v else "–" for v in vals]   # a bucket can be empty (no test tokens)
        L.append(f"| `{m}` | " + " | ".join(cells) + " |")

    L += ["", "## `profile_lr` details", "", "Standardised logistic-regression weights (positive = more likely wrong):", "",
          "| feature | " + " | ".join(tracks) + " |", "|---|" + "---|" * len(tracks)]
    for f in ProfileLR.features:
        L.append(f"| {f} | " + " | ".join(f"{r['models']['profile_lr']['coef'][f]:+.2f}" for r in results) + " |")
    L += ["", f"Calibration ({tracks[0]}): predicted vs actual error rate, by decile of prediction", "",
          "| predicted | actual | tokens |", "|---|---|---|"]
    for row in results[0]["models"]["profile_lr"]["calibration"]:
        L.append(f"| {row['predicted']:.3f} | {row['actual']:.3f} | {row['tokens']:,} |")

    L += ["", "## Metrics", "",
          "- **skill** (headline) = 1 - LogLoss(model) / LogLoss(base_rate). 0 = no better than knowing how hard the task "
          "is on average; 1 = perfect; negative = worse than that. Rewards both ranking and honest probabilities.",
          "- **AUROC**: chance a random wrong token gets a higher prediction than a random right one, pooled over all "
          "test tokens. SLAM's official metric on the same split, all formats: 2018 baseline 0.774 / 0.746 / 0.771 "
          "(en_es / es_en / fr_en), best published 0.864 / 0.839 / 0.860 (Hu et al. 2020).",
          "- **AUROC within exercise**: AUROC over pairs of tokens from the same exercise (one wrong, one right). Same "
          "learner, same moment, so *who* is weak cancels out; measures whether the model knows *which* words this learner "
          "will miss. (Per-learner AUROC was dropped: a learner's past error rate is mechanically anti-correlated with "
          "their remaining answers, which unfairly penalises history-based features.)",
          "- **F1@0.5**: SLAM's secondary metric. With error rates ~20%, most predictions stay below 0.5, so it is low "
          "for all models; kept only for comparability."]
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tracks", nargs="+", default=data.TRACKS)
    ap.add_argument("--formats", nargs="+", default=["reverse_translate"])
    args = ap.parse_args()
    formats = tuple(args.formats)
    results = [run_track(t, formats) for t in args.tracks]
    REPORTS.mkdir(exist_ok=True)
    stem = "_".join(formats)
    (REPORTS / f"{stem}.json").write_text(json.dumps(results, indent=1))
    (REPORTS / f"{stem}.md").write_text(report(results, formats))
    print(f"wrote {REPORTS / stem}.md")


if __name__ == "__main__":
    main()
